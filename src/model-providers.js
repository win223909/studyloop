const normalizeBase = (value) =>
  String(value || '')
    .trim()
    .replace(/\/+$/, '');
export function detectProvider(values) {
  const base = normalizeBase(values.LLM_BASE_URL);
  const exact = MODEL_PROVIDERS.find(
    (item) =>
      item.protocol === values.LLM_PROVIDER &&
      item.base &&
      [item.base, ...(item.aliases || [])].some((url) => normalizeBase(url) === base),
  );
  if (exact) return exact.id;
  if (values.LLM_PROVIDER === 'openai-compatible') {
    try {
      const url = new URL(base);
      if (
        url.protocol === 'https:' &&
        !url.username &&
        !url.password &&
        !url.search &&
        !url.hash &&
        /\.(openai\.azure\.com|services\.ai\.azure\.com)$/.test(url.hostname) &&
        url.pathname === '/openai/v1'
      )
        return 'azure-openai';
    } catch {
      /* Incomplete custom URLs stay custom while typing. */
    }
  }
  return 'custom';
}

export function searchProviders(query = '') {
  const words = query.toLocaleLowerCase().trim().split(/\s+/).filter(Boolean);
  return MODEL_PROVIDERS.filter((item) => {
    const group = PROVIDER_GROUPS.find((group) => group.id === item.group);
    const haystack = [
      item.id,
      item.label,
      item.labelZh,
      item.keywords,
      group?.label,
      group?.labelZh,
    ]
      .filter(Boolean)
      .join(' ')
      .toLocaleLowerCase();
    return words.every((word) => haystack.includes(word));
  });
}
